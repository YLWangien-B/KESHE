/* =============================================================================
 *  ds_sort.h  —  插入排序（不使用模板）
 *
 *  为什么单独放一个文件：
 *    智能导诊要把推荐的科室按得分从大到小排好，用的是插入排序。
 *    一开始这段逻辑写在 Triage 类里，于是它和「科室」「得分」这些业务概念
 *    绑在一起，想单独验证这个算法就得把整个业务层都拖进来。
 *    抽到这里之后，它只认「一个 TriageItem 数组 + 一个容量上限」，
 *    也就能脱离界面单独验证 —— 用几个手写的 TriageItem 就能跑。
 *
 *  ---------------------------------------------------------------------------
 *  为什么这里不再用模板
 *
 *  原来是 `template <typename T, typename Less> void insertSorted(...)`，
 *  好处是「任何元素类型都能用，排序规则也能换」。课程要求不使用模板，
 *  所以改成只排 TriageItem 的具体函数，比较也直接写成「比 score」。
 *
 *  代价是它现在和 TriageItem 这个类型绑在一起 —— 这是为了满足课程约束而
 *  明确选择的代价，不是疏忽。如果需要给别的类型排序，照抄这个函数把元素类型
 *  和比较那行改掉即可（仍然是插入排序，逻辑一模一样）。
 *  ---------------------------------------------------------------------------
 *
 *  本例的用途：结果集很小（最多几条），而且要求「得分相同的保持先来后到」
 *  这种稳定行为 —— 插入排序天然稳定，正合适。
 * ========================================================================== */
#pragma once

#include "ds_list.h"

// TriageItem 放在这里而不是 service.h：它是「一条推荐结果」，而排序的对象
// 就是它。放在同一个文件里，这个文件才是自洽的一层 —— 想单独验证插入排序，
// 只需要 include 本文件，不必先把业务层拖进来。
constexpr int kMaxMatchedPerDept = 8;  // 每个科室最多记几个命中的症状

// 一个推荐科室
struct TriageItem {
  int dept;                         // 科室下标
  int score;                        // 匹配得分（命中症状的权重之和）
  int matchCount;                   // 命中的症状个数
  int matched[kMaxMatchedPerDept];  // 命中的症状顶点号，用于说明推荐理由
};

// -----------------------------------------------------------------------------
//  把 v 按得分降序插入到「已按得分降序排好」的数组 [0, n) 里，容量上限 cap。
//
//  a、n 都是引用：这个函数只负责插入，不改变数组的容量上限；
//  插入成功时 n 加一，因为满了而被丢弃时 n 不变。
//
//  数组里从头到尾依次满足「前一个的得分 >= 后一个的得分」。
//
//  **满了之后的行为**：数组已经有 cap 个元素时，只有当 v 的得分**严格高于**
//  最后一名才把它挤掉；排不进去就整个丢弃。这正是「只保留前 cap 名」的语义 ——
//  更好的成绩本来就该挤进来。判断用严格不等号，于是和最后一名同分的 v
//  挤不进去，先来的不会被顶掉，同样的输入永远得到同样的次序。
//
//  为什么稳定性在本项目重要：导诊结果里经常出现同分（比如「胸闷+咳嗽」让
//  心血管内科和呼吸内科都得 5 分）。如果次序不确定，那么每次运行推荐的
//  「第 1 名」都可能不一样，用户会觉得系统不可靠。用严格不等号 = 先来后到，
//  结果可复现。
//
//  复杂度：O(n) 插入（要后移元素）。n 最多 5，可以忽略。
// -----------------------------------------------------------------------------
inline void insertSorted(TriageItem* a, int& n, int cap, const TriageItem& v) {
  if (n < cap) {
    // 还有空位：从后往前扫，只要「v 的得分比前一个高」，就把那个元素
    // 后移一格，直到遇到一个得分不低于 v 的为止。
    int pos = n;
    while (pos > 0 && v.score > a[pos - 1].score) {
      a[pos] = a[pos - 1];
      --pos;
    }
    a[pos] = v;
    ++n;
    return;
  }

  // 已经满了：得分没能超过最后一名就丢弃（严格不等号，同分不挤）
  if (v.score <= a[cap - 1].score) return;

  int pos = cap - 1;
  while (pos > 0 && v.score > a[pos - 1].score) {
    a[pos] = a[pos - 1];
    --pos;
  }
  a[pos] = v;
}

/* =============================================================================
 *  ds_sort.h  —  插入排序（通用版本）
 *
 *  为什么单独放一个文件：
 *    智能导诊要把推荐的科室按得分从大到小排好，用的是插入排序。
 *    一开始这段逻辑写在 Triage 类里，于是它和「科室」「得分」这些业务概念
 *    绑在一起，想单独验证这个算法就得把整个业务层都拖进来。
 *    抽到这里之后，它只认「一个数组 + 一个排序规则」，任何元素类型都能用，
 *    也就能脱离业务单独自检。
 *
 *  本例的用途：结果集很小（最多几条），而且要求「得分相同的保持先来后到」
 *  这种稳定行为 —— 插入排序天然稳定，正合适。
 * ========================================================================== */
#pragma once

// -----------------------------------------------------------------------------
//  把 v 插入到「已按规则排好序」的数组 [0, n) 里。
//
//  a、n 都是引用：这个函数只负责插入，不改变数组的容量上限；
//  插入成功时 n 加一，因为满了而被丢弃时 n 不变。
//
//  排序规则由 Less 给出，约定是：
//      Less(x, y) 为真   <=>   x 应当排在 y 前面
//  数组里从头到尾依次满足「前一个排在后一个前面」。
//
//  **满了之后的行为**：数组已经有 cap 个元素时，只有当 v「能排在最后一名前面」
//  才把它挤掉；排不进去就整个丢弃。这正是「只保留前 cap 名」的语义 ——
//  更好的成绩本来就该挤进来。判断用严格不等号，于是和最后一名同分的 v
//  挤不进去，先来的不会被顶掉，同样的输入永远得到同样的次序。
// -----------------------------------------------------------------------------
template <typename T, typename Less>
void insertSorted(T* a, int& n, int cap, const T& v, Less less) {
  if (n < cap) {
    // 还有空位：从后往前扫，只要「v 应当排在前一个元素前面」，就把那个元素
    // 后移一格，直到遇到一个应当排在 v 前面的为止。
    int pos = n;
    while (pos > 0 && less(v, a[pos - 1])) {
      a[pos] = a[pos - 1];
      --pos;
    }
    a[pos] = v;
    ++n;
    return;
  }

  // 已经满了：排不进最后一名前面就丢弃
  if (!less(v, a[cap - 1])) return;

  int pos = cap - 1;
  while (pos > 0 && less(v, a[pos - 1])) {
    a[pos] = a[pos - 1];
    --pos;
  }
  a[pos] = v;
}

// -----------------------------------------------------------------------------
//  两种常用的排序规则，直接拿来用即可。
//
//  Less 回答的是「第一个参数排不排在第二个参数前面」。
// -----------------------------------------------------------------------------

// 分数从高到低：a 的分数比 b 高，a 就排在 b 前面
struct GreaterScore {
  template <typename T>
  bool operator()(const T& a, const T& b) const {
    return a.score > b.score;
  }
};

// 数值从小到大：a 比 b 小，a 就排在 b 前面
template <typename T>
struct Ascending {
  bool operator()(const T& a, const T& b) const { return a < b; }
};

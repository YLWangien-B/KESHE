/* =============================================================================
 *  db.cpp  —  数据总库的唯一实例
 *
 *  数据总库 Hospital 体积大于默认的 1MB 线程栈，不能作为局部变量，
 *  因此用「函数内静态对象」持有：第一次调用时构造，程序结束才销毁。
 *
 *  为什么单独放一个文件（而不是写在 main.cpp 里）：
 *    本工程有三个可执行程序 —— hospital（主程序）、selfcheck（自检）、
 *    gen_data（测试数据生成器），它们各自有一个 main。
 *    如果把 db() 的定义写在 main.cpp 里，selfcheck 就链接不到它，
 *    只能自己再定义一份，于是同一个函数出现两份实现。
 *    放在这里，谁需要谁链接，定义始终只有一份。
 * ========================================================================== */
#include "model.h"

Hospital& db() {
  static Hospital instance;
  return instance;
}

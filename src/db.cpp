/* =============================================================================
 *  db.cpp  —  数据总库的唯一实例
 *
 *  数据总库 Hospital 有 370444 字节（约 361 KB）：没有超过默认的 1MB 线程栈，
 *  但一个大对象放在栈上不是好习惯，因此用「静态存储区」持有。
 *
 *  为什么单独放一个文件（而不是写在 main.cpp 里）：
 *    本工程有两个主程序 —— hospital（字符界面）与 hospital_qt（Qt 图形界面），
 *    它们各自有一个 main，但共用同一个数据总库。
 *    如果把 db() 的定义写在 main.cpp 里，图形界面程序就链接不到它，
 *    只能自己再定义一份，于是同一个函数出现两份实现、两份状态。
 *    放在这里，谁需要谁链接，定义始终只有一份。
 *
 *  两种运行模式（见 shared_db.h）：
 *    单进程模式  没有调用 shared::open()，返回进程内的静态实例 —— 与拆分之前一致。
 *    共享模式    调用了 shared::open() 之后，返回共享内存里那一份，
 *                于是患者端与管理端看到的是同一份数据。
 * ========================================================================== */
#include "shared_db.h"

Hospital& db() { return shared::hospital(); }
